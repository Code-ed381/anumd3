export function OwnerNav() {
  const pathname = usePathname();
  const router = useRouter();
  const [open, setOpen] = useState(false);

  async function logout() {
    const supabase = createBrowserSupabase();
    await supabase.auth.signOut();
    router.replace("/owner/login");
    router.refresh();
  }

  return (
    <header className="sticky top-0 z-20 border-b border-[color:var(--border)] bg-[color:var(--card)]">
      <div className="h-1 bg-[color:var(--brand-green-dark)]" aria-hidden />
      <div className="mx-auto flex max-w-5xl items-center justify-between px-4 py-3">
        <Link href="/owner/dashboard" className="flex shrink-0 items-center gap-2.5">
          <Image
            src="/logo.jpeg"
            alt=""
            width={36}
            height={36}
            className="h-9 w-9 rounded-lg object-cover ring-1 ring-[color:var(--border)]"
          />
        </Link>

        <nav className="hidden items-center gap-1 sm:flex">
          {LINKS.map((link) => {
            const active = pathname.startsWith(link.href);
            return (
              <Link
                key={link.href}
                href={link.href}
                className={`flex items-center gap-1.5 rounded-full px-3 py-1.5 text-sm font-medium transition-colors ${
                  active
                    ? "bg-[color:var(--brand-green-dark)] text-white"
                    : "text-[color:var(--muted)] hover:bg-[color:var(--brand-green)]/10 hover:text-[color:var(--foreground)]"
                }`}
              >
                {link.icon}
                {link.label}
              </Link>
            );
          })}
        </nav>

        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={() => void logout()}
            className="hidden items-center gap-1.5 rounded-full px-3 py-1.5 text-sm font-medium text-[color:var(--muted)] transition-colors hover:bg-red-50 hover:text-red-600 sm:flex"
          >
            {LOGOUT_ICON}
            Log out
          </button>
          <button
            type="button"
            onClick={() => setOpen(!open)}
            className="rounded-lg p-1.5 text-[color:var(--muted)] hover:bg-[color:var(--brand-green)]/10 sm:hidden"
            aria-label="Toggle menu"
          >
            <svg
              xmlns="http://www.w3.org/2000/svg"
              fill="none"
              viewBox="0 0 24 24"
              strokeWidth={2}
              stroke="currentColor"
              className="h-5 w-5"
            >
              {open ? (
                <path
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  d="M6 18L18 6M6 6l12 12"
                />
              ) : (
                <path
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  d="M3.75 6.75h16.5M3.75 12h16.5m-16.5 5.25h16.5"
                />
              )}
            </svg>
          </button>
        </div>
      </div>

      {open && (
        <nav className="border-t border-[color:var(--border)] px-4 pb-3 pt-2 sm:hidden">
          <div className="flex flex-col gap-1">
            {LINKS.map((link) => {
              const active = pathname.startsWith(link.href);
              return (
                <Link
                  key={link.href}
                  href={link.href}
                  onClick={() => setOpen(false)}
                  className={`flex items-center gap-2 rounded-lg px-3 py-2 text-sm font-medium ${
                    active
                      ? "bg-[color:var(--brand-green-dark)] text-white"
                      : "text-[color:var(--muted)] hover:bg-[color:var(--brand-green)]/10 hover:text-[color:var(--foreground)]"
                  }`}
                >
                  {link.icon}
                  {link.label}
                </Link>
              );
            })}
            <button
              type="button"
              onClick={() => void logout()}
              className="flex items-center gap-2 rounded-lg px-3 py-2 text-left text-sm font-medium text-[color:var(--muted)] hover:bg-red-50 hover:text-red-600"
            >
              {LOGOUT_ICON}
              Log out
            </button>
          </div>
        </nav>
      )}
    </header>
  );
}
